/**
 * Storage medium by device generation: iPhones use NVMe from the 6s onwards,
 * iPad Pro models use NVMe, everything else is flash/eMMC.
 */
export function getDeviceDiskType(productType: string): string | null {
  if (/^iPhone/.test(productType)) {
    const major = parseInt(productType.split(",")[0].replace("iPhone", ""), 10);
    return major >= 8 ? "nvme" : "emmc";
  }
  if (nvmeIpadProducts.has(productType)) return "nvme";
  if (/^iPad/.test(productType)) return "flash";
  return "flash";
}
